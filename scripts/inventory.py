#!/usr/bin/env python3
"""Stage 0d: file tree, per-run checks and notebook<->run map. No LLM. Output: facts/inventory.md"""
import sys
from pathlib import Path

root = Path(sys.argv[1] if len(sys.argv) > 1 else ".").resolve()
out = root / "facts" / "inventory.md"
out.parent.mkdir(parents=True, exist_ok=True)
SKIP = {"facts", ".git", ".claude", "__pycache__", "scripts", "node_modules"}

def human(n):
    for u in ("B", "K", "M", "G"):
        if n < 1024 or u == "G":
            return f"{n}B" if u == "B" else f"{n:.1f}{u}"
        n /= 1024

L = ["# Inventory (generated by scripts/inventory.py; no LLM)\n", "## File tree", "```"]
def walk(d, depth=0):
    for p in sorted(d.iterdir(), key=lambda x: (x.is_file(), x.name)):
        if p.name in SKIP:
            continue
        if p.is_dir():
            L.append("  " * depth + p.name + "/"); walk(p, depth + 1)
        else:
            L.append("  " * depth + f"{p.name} ({human(p.stat().st_size)})")
walk(root)
L += ["```", "", "## Per-run checks"]

models = root / "models"
EXPECT = ["best_projectors.pt", "test_metrics.json", "test_predictions.csv", "training_history.csv"]
run_names = {}
for d in sorted(p for p in models.iterdir() if p.is_dir()):
    names = {p.name for p in d.iterdir()}
    if "best_lora_adapters" not in names:
        L.append(f"- {d.name}: NOT a LoRA run folder. files: {sorted(names)}")
        for n in sorted(names):
            if "partial" in n.lower():
                L.append(f"  - FLAG: '{n}' looks like an interrupted/partial output")
        continue
    run_names[d.name.lower().replace("-", "_")] = d.name
    flags = [f"missing {e}" for e in EXPECT if e not in names]
    if "run_config.json" not in names:
        flags.append("no run_config.json (hyperparameters must come from notebook/adapter_config)")
    adapters = sorted(p.name for p in (d / "best_lora_adapters").iterdir())
    L.append(f"- {d.name}: adapter files={adapters}; flags={flags or 'none'}")

L += ["", "## Notebook -> run map (heuristic name match; verify before trusting)"]
for nb in sorted((root / "notebooks").glob("*.ipynb")):
    key = nb.stem.lower().replace("qwen2-vl-1.5b", "qwen2_1_5b").replace("-", "_")
    match = run_names.get(key)
    size = nb.stat().st_size
    note = " [SMALL: outputs likely cleared, take numbers from metrics files]" if size < 500_000 else ""
    L.append(f"- notebooks/{nb.name} ({human(size)}) -> {match or 'NO RUN MATCH (map manually)'}{note}")

out.write_text("\n".join(L) + "\n", encoding="utf-8")
print(f"wrote {out}")
