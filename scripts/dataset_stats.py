#!/usr/bin/env python3
"""Stage 0c: counts, columns and hashes for manifests / audit / predictions. No LLM.
Output: facts/dataset/dataset_stats.md"""
import csv, hashlib, json, sys
from collections import Counter, defaultdict
from pathlib import Path

csv.field_size_limit(sys.maxsize)
root = Path(sys.argv[1] if len(sys.argv) > 1 else ".").resolve()
models = root / "models"
out = root / "facts" / "dataset"
out.mkdir(parents=True, exist_ok=True)

def sha(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()[:12]

def csv_info(p):
    with open(p, newline="", encoding="utf-8", errors="replace") as f:
        r = csv.reader(f); header = next(r, []); n = sum(1 for _ in r)
    return header, n

def jsonl_info(p):
    n, first = 0, None
    with open(p, encoding="utf-8", errors="replace") as f:
        for line in f:
            if line.strip():
                n += 1
                if first is None:
                    first = line.strip()
    return n, first

L = ["# Dataset stats (generated by scripts/dataset_stats.py; no LLM)\n"]
groups = defaultdict(list)
dirs = sorted(p for p in models.iterdir() if p.is_dir())

L.append("## Manifests (line counts)")
sample = None
for d in dirs:
    for name in ("train_manifest.jsonl", "validation_manifest.jsonl", "test_manifest.jsonl"):
        p = d / name
        if p.exists():
            n, first = jsonl_info(p)
            L.append(f"- {d.name}/{name}: lines={n}")
            groups[name].append((sha(p), d.name))
            if name == "test_manifest.jsonl" and sample is None:
                try:
                    keys = list(json.loads(first).keys())
                except Exception:
                    keys = "unparseable"
                sample = (d.name, keys, first[:800])
if sample:
    L += ["", f"## Manifest record format (first test record of {sample[0]})", f"- top-level keys: {sample[1]}", "```", sample[2], "```"]

L.append("\n## Audit CSV (source_to_kaggle_pair_audit.csv)")
first_audit = None
for d in dirs:
    p = d / "source_to_kaggle_pair_audit.csv"
    if p.exists():
        header, n = csv_info(p)
        L.append(f"- {d.name}: rows={n}, columns={header}")
        groups["source_to_kaggle_pair_audit.csv"].append((sha(p), d.name))
        first_audit = first_audit or p
if first_audit:
    with open(first_audit, newline="", encoding="utf-8", errors="replace") as f:
        rows = list(csv.DictReader(f))
    L.append(f"\n### Low-cardinality columns in {first_audit.parent.name} audit CSV")
    for col in (rows[0].keys() if rows else []):
        c = Counter(r[col] for r in rows)
        if len(c) <= 10:
            L.append(f"- {col}: {dict(c)}")

L.append("\n## Prediction CSVs")
for d in dirs:
    for p in sorted(d.glob("*predictions*.csv")):
        header, n = csv_info(p)
        L.append(f"- {d.name}/{p.name}: rows={n}, columns={header}")

L.append("\n## File identity across runs (same hash = byte-identical file)")
for name, items in groups.items():
    by_hash = defaultdict(list)
    for h, run in items:
        by_hash[h].append(run)
    for h, runs in by_hash.items():
        L.append(f"- {name} sha256={h}: identical in {len(runs)} runs: {', '.join(runs)}")

(out / "dataset_stats.md").write_text("\n".join(L) + "\n", encoding="utf-8")
print(f"wrote {out / 'dataset_stats.md'} ({len(L)} lines)")
